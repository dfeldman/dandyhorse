#!/usr/bin/env python3
"""Generate src/registry/entries.generated.ts and src/quirks/flags.generated.ts.

Source of truth: docs/devices/quirks.yaml (entries) and docs/devices/quirks.md (flag vocabulary).
Usage: python3 scripts/gen_registry.py [path/to/docs/devices]
"""
import json, os, re, sys
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DOCS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', 'docs', 'devices')

MATCH_KEYS = {
    'name_prefix', 'name_exact', 'name_contains', 'name_regex', 'case_sensitive', 'name_length',
    'name_length_any', 'exclude_prefix', 'name_excludes_chars', 'adv_service', 'adv_service_absent',
    'gatt_has', 'or_gatt_has', 'user_option',
}
UUID_KEYS = {'adv_service', 'adv_service_absent', 'gatt_has', 'or_gatt_has'}
BASE = '-0000-1000-8000-00805f9b34fb'
UUID128 = re.compile(r'^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')


def norm_uuid(u):
    s = str(u).strip().lower()
    if s.startswith('0x'):
        s = s[2:]
    if re.fullmatch(r'[0-9a-f]{4}', s):
        return '0000' + s + BASE
    if re.fullmatch(r'[0-9a-f]{8}', s):
        return s + BASE
    if UUID128.match(s):
        return s
    raise ValueError('bad uuid %r' % u)


def as_list(v):
    return [str(x) for x in (v if isinstance(v, list) else [v])]


def main():
    with open(os.path.join(DOCS, 'quirks.yaml')) as f:
        devices = yaml.safe_load(f)['devices']
    with open(os.path.join(DOCS, 'quirks.md')) as f:
        flags = sorted(set(re.findall(r'^\|\s*`([a-z0-9_]+)`\s*\|', f.read(), re.M)))

    out, uuids = [], set()
    for e in devices:
        m = e.get('match') or {}
        unknown = set(m) - MATCH_KEYS
        if unknown:
            raise SystemExit('%s: unknown match keys %s' % (e['id'], unknown))
        match = {}
        for k, v in m.items():
            if k in UUID_KEYS:
                match[k] = [norm_uuid(x) for x in as_list(v)]
                uuids.update(match[k])
            elif k in ('name_prefix', 'name_contains', 'name_regex', 'exclude_prefix', 'name_excludes_chars'):
                match[k] = as_list(v)
            elif k == 'name_length_any':
                match[k] = [int(x) for x in v]
            elif k == 'name_exact':
                match[k] = str(v)
            else:
                match[k] = v
        for fl in (e.get('flags') or {}):
            if fl not in flags:
                raise SystemExit('%s: flag %s not defined in quirks.md' % (e['id'], fl))
        entry = {
            'id': e['id'], 'class': e['class'], 'protocol': e['protocol'],
            'recommend': e.get('recommend', 'support'), 'match': match,
            'flags': sorted((e.get('flags') or {}).keys()),
            'params': e.get('params') or {},
            'doc': e.get('doc'),
        }
        if e.get('notes'):
            entry['notes'] = ' '.join(str(e['notes']).split())
        out.append(entry)

        def walk(v):
            if isinstance(v, str):
                for u in re.findall(r'[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}', v):
                    uuids.add(u.lower())
                if re.fullmatch(r'0x[0-9A-Fa-f]{4}', v):
                    uuids.add(norm_uuid(v))
            elif isinstance(v, dict):
                for x in v.values(): walk(x)
            elif isinstance(v, list):
                for x in v: walk(x)
        walk(e.get('params'))

    header = '// GENERATED by scripts/gen_registry.py from docs/devices/quirks.yaml. Do not edit.\n'
    with open(os.path.join(ROOT, 'src', 'registry', 'entries.generated.ts'), 'w') as f:
        f.write(header)
        f.write("import type { RegistryEntry } from './types.ts';\n\n")
        f.write('export const REGISTRY_ENTRIES: readonly RegistryEntry[] = ')
        f.write(json.dumps(out, indent=1, ensure_ascii=False, default=str))
        f.write(';\n\n/** Every UUID mentioned by the registry (services and characteristics), 128-bit lowercase. */\n')
        f.write('export const REGISTRY_UUIDS: readonly string[] = ')
        f.write(json.dumps(sorted(uuids), indent=1))
        f.write(';\n')
    with open(os.path.join(ROOT, 'src', 'quirks', 'flags.generated.ts'), 'w') as f:
        f.write(header.replace('quirks.yaml', 'quirks.md'))
        f.write('export const QUIRK_FLAGS = ' + json.dumps(flags, indent=1) + ' as const;\n\n')
        f.write('export type QuirkFlag = (typeof QUIRK_FLAGS)[number];\n')
    # Language-neutral copy for native ports (Swift, Kotlin, C++): same data, plain JSON.
    os.makedirs(os.path.join(ROOT, 'generated'), exist_ok=True)
    with open(os.path.join(ROOT, 'generated', 'registry.json'), 'w') as f:
        json.dump({'entries': out, 'flags': flags, 'uuids': sorted(uuids)}, f, indent=1, ensure_ascii=False, default=str)
    print('entries %d, flags %d, uuids %d' % (len(out), len(flags), len(uuids)))


if __name__ == '__main__':
    main()
