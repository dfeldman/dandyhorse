#!/usr/bin/env python3
"""
Writes library.json for the bushes: a shrub layer for the wood floor, the hedgerow and the moor.

Per species a count, a height range and a width multiplier, so one species gives everything from a
knee-high scrub to something you could not see over. Goes into public/plants beside the card plants.

    python3 tools/bushgen/library.py [--per-species 10]
"""
import argparse
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent

TABLE = {
    'bush_green':   {'count': 14, 'height': (0.8, 2.4), 'width': (0.85, 1.25)},
    'bramble':      {'count': 12, 'height': (0.6, 1.6), 'width': (0.9, 1.4)},
    'sagebrush':    {'count': 10, 'height': (0.5, 1.4), 'width': (0.85, 1.2)},
    'hazel':        {'count': 12, 'height': (1.8, 4.0), 'width': (0.85, 1.2)},
    'hawthorn':     {'count': 12, 'height': (1.2, 3.2), 'width': (0.85, 1.2)},
    'elder':        {'count': 10, 'height': (1.5, 3.4), 'width': (0.85, 1.2)},
    'dogwood':      {'count': 10, 'height': (1.0, 2.6), 'width': (0.85, 1.2)},
    'willow_scrub': {'count': 10, 'height': (1.2, 3.0), 'width': (0.85, 1.25)},
    'rhododendron': {'count': 10, 'height': (1.0, 2.6), 'width': (0.9, 1.3)},
    'juniper_scrub': {'count': 10, 'height': (0.4, 1.4), 'width': (0.9, 1.4)},
    'mugo_pine':    {'count': 10, 'height': (0.9, 2.4), 'width': (0.85, 1.25)},
}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--seed', type=int, default=2030)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    out_list = []
    for species, t in TABLE.items():
        lo, hi = t['height']
        for i in range(t['count']):
            h = round(lo + (hi - lo) * rng.random() ** 1.3, 2)
            sets = [f'height=[{h},{round(h * 0.05, 2)}]',
                    f'envelope.width_scale={round(rng.uniform(*t["width"]), 2)}',
                    f'leaves.light_var={round(rng.uniform(0.1, 0.2), 2)}']
            out_list.append({'species': species, 'seed': 11000 + len(out_list), 'name': f'{species}_{i + 1:03d}', 'set': sets})
    out = HERE / 'library.json'
    out.write_text(json.dumps({'about': 'Generated by library.py; do not edit by hand.', 'total': len(out_list), 'trees': out_list}, indent=1))
    print(f'{len(out_list)} bushes -> {out}')


if __name__ == '__main__':
    main()
