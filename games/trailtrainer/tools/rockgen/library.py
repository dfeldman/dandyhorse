#!/usr/bin/env python3
"""
Writes library.json for the rocks.

An area is mostly one kind of rock, so the library is organised by TYPE (the surface: grey granite,
dark stratified, pale limestone, mossy forest rock ...) and gives every type plenty of variety inside
it: single boulders in a dozen shape archetypes (round, egg, flat, slab, tall, long, block, shard,
wedge, dome, lumpy, split), groups of two to four, and pebble or scree fields, each at a range of sizes.
Pick a type per region and the shapes will differ while the rock stays the same rock.

    python3 tools/rockgen/library.py [--per-type 24]
"""
import argparse
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent

TYPES = ['grey', 'dark', 'cracked', 'pale', 'lichen', 'mossy', 'bare', 'scree', 'river']
# forms within a type: (name, share, sets)
FORMS = [
    ('single', 0.6, lambda rng, k: [f'size=[{round(0.4 * k, 2)},{round(1.5 * k, 2)}]']),
    ('group', 0.25, lambda rng, k: ['boulders=[2,4]', 'pebbles=[6,16]', 'pebble_size=[0.1,0.3]', 'field_radius=1.2',
                                    f'size=[{round(0.5 * k, 2)},{round(1.3 * k, 2)}]', 'budget=[2000,4500]']),
    ('field', 0.15, lambda rng, k: ['boulders=[0,0]', f'pebbles=[{int(30 * k)},{int(80 * k)}]', 'pebble_size=[0.08,0.4]',
                                    f'field_radius={round(2.2 * k, 2)}', 'size=[1,1]', 'budget=[1500,4000]']),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('--per-type', type=int, default=24)
    ap.add_argument('--seed', type=int, default=2028)
    args = ap.parse_args()
    rng = random.Random(args.seed)
    rocks = []
    for t in TYPES:
        spec = json.loads((HERE / 'species' / f'{t}.json').read_text())
        for i in range(args.per_type):
            u = rng.random()
            form = FORMS[0] if u < 0.6 else FORMS[1] if u < 0.85 else FORMS[2]
            if t == 'river' and form[0] == 'group':
                form = FORMS[2]
            k = round(rng.uniform(0.7, 1.4), 2)
            sets = form[2](rng, k)
            if form[0] == 'single':
                # one shape per single, drawn by the type's weights, so the index can say what it is
                shapes, weights = spec['shapes'], spec['shape_weights']
                shape = rng.choices(shapes, weights)[0]
                sets.append(f'shapes=["{shape}"]')
            sets += [f'moss={round(max(0.0, spec.get("moss", 0) * rng.uniform(0.5, 1.3)), 2)}',
                     f'lichen={round(max(0.0, spec.get("lichen", 0) * rng.uniform(0.4, 1.4)), 2)}',
                     f'roughness={round(spec.get("roughness", 0.14) * rng.uniform(0.7, 1.4), 3)}']
            rocks.append({'species': t, 'seed': 7000 + len(rocks), 'name': f'{t}_{i + 1:03d}', 'form': form[0], 'set': sets})
    out = HERE / 'library.json'
    out.write_text(json.dumps({'about': 'Generated by library.py from its type table; do not edit by hand.',
                               'total': len(rocks), 'trees': rocks}, indent=1))
    print(f'{len(rocks)} rocks -> {out}')


if __name__ == '__main__':
    main()
